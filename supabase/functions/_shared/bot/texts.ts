// /help (= /start) by spec §5: one HTML message < 4096 chars, lines depend on the accounts mode, Groq key,
// reminder setting and the chat. No npm imports.
import { isMulti, partnerName } from './ctx.ts'
import type { Ctx } from './ctx.ts'

export const NEED_APP = 'Сначала открой приложение — оно создаст настройки, и тогда бот заработает.'
export const IN_APP = 'Это делается в приложении — там видно и можно отменить.'
export const SHORT_HELP = 'Не вижу суммы. Например: кофе 80\nВся инструкция — /help'

export function helpText(ctx: Ctx, greeting = false): string {
  const multi = isMulti(ctx.settings)
  const owner = ctx.author === 'owner'
  const partner = partnerName(ctx.settings)
  const days = ctx.settings.remind_after_days
  const L: (string | false)[] = [
    greeting && (owner ? 'Привет!' : `Привет, ${partner}!`),
    greeting && '',
    '<b>📒 Как пользоваться ботом</b>',
    '',
    '<b>✍️ Траты — пиши как говоришь</b>',
    '• кофе 80 — гривны по умолчанию',
    '• такси 15 eur · обед 12$ · продукты 200 лей',
    '• кофе 50 сигареты 30 молоко 40 — несколько сразу',
    '• 2 кофе по 50 — посчитаю сам',
    '• вчера атб 420 · 21.10 аптека 300',
    multi && '• кофе 80 прокредит — с нужного счёта',
    '• +2500 usd зп — доход',
    ctx.groq ? '• 🎤 Можно голосом. Понимаю сленг: сотка, косарь, 2к' : '• Понимаю сленг: сотка, косарь, 2к',
    '',
    '<b>💱 Счета и обмен</b>',
    multi && '• перевёл 200$ с основного на наличные',
    '• поменял 100$ на 4100 грн',
    '• на руках 3500$ — сверю и поправлю',
    multi && '• удали счёт Монобанк',
    '',
    '<b>🎯 Цели, лимиты, категории</b>',
    '• цель машина 500 — отложить · цель машина -200 — забрать',
    '• новая цель отпуск 2000$ к июню',
    '• лимит на кафе 150$',
    '• создай категорию Спорт и впиши туда зал 500',
    '',
    '<b>✏️ Если ошибся</b>',
    '• Ответь на моё сообщение: «90», «вчера», «наличные», «кафе» или «удали»',
    multi ? '• Кнопки под ответом: Категория · Счёт · Отменить' : '• Кнопки под ответом: Категория · Отменить',
    '• /undo — отменить последнюю запись',
    owner && '• /clear — удалить записи за период (вернуть можно 24 часа)',
    '',
    '<b>📊 Узнать</b> (можно словами)',
    '• /today — сегодня · /week — неделя · /month — месяц',
    '• /left — сколько можно тратить сегодня',
    '• /balance — сколько денег на счетах',
    '• /goals — цели · /limits — лимиты',
    '• найди такси · сколько на кафе · кто сколько потратил',
    '• /export — выгрузка для Excel',
    '• /ping — проверка связи («сделай проверку»)',
    '',
    '<b>⚙️ Настройки</b>',
    '• /settings — итог дня, напоминания, валюта',
    '• посадка 20 декабря · запас 1000$ · по умолчанию леи',
    '',
    '<b>🤖 Что я делаю сам</b>',
    '• Подбираю категорию и учусь на твоих правках',
    '• Пишу, сколько осталось на сегодня, и слежу за лимитами',
    days > 0 && `• Напоминаю, если ${days} ${days >= 5 ? 'дней' : 'дня'} нет записей`,
    '• Дважды в день проверяю, что база жива',
    owner && '• По воскресеньям присылаю резервную копию',
    owner && ctx.partnerChatId !== null && `• Сообщаю, что записала ${partner}`,
    !owner && '• Твои траты сразу видит Кирилл',
  ]
  return L.filter((x): x is string => x !== false).join('\n')
}
