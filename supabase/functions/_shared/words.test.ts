import { describe, expect, it } from 'vitest'
import { numberWords } from './words.ts'

describe('numberWords', () => {
  it.each([
    ['кофе восемьдесят', 'кофе 80'],
    ['сто пятьдесят', '150'],
    ['тысяча двести', '1200'],
    ['полтора', '1.5'],
    ['двадцать пять с половиной', '25.5'],
    ['молоко сорок стики 300', 'молоко 40 стики 300'],
    ['двадцать один', '21'],
    ['две пачки сигарет по 30', '2 пачки сигарет по 30'],
    ['дві тисячі', '2000'],
  ])('%s -> %s', (from, to) => expect(numberWords(from)).toBe(to))

  it.each([
    ['сотка', '100'],
    ['полтос', '50'],
    ['пятихатка', '500'],
    ['косарь', '1000'],
    ['2к', '2000'],
    ['2k', '2000'],
    ['пол косаря', '500'],
    ['полторы штуки', '1500'],
    ['2 косаря', '2000'],
    ['закинул сотку на такси и полтос на кофеёк', 'закинул 100 на такси и 50 на кофеёк'],
  ])('slang %s -> %s', (from, to) => expect(numberWords(from)).toBe(to))

  it('leaves a lone «один», plain words and digits alone; keeps punctuation', () => {
    expect(numberWords('один кофе 50')).toBe('один кофе 50')
    expect(numberWords('кофе 80, такси сто,')).toBe('кофе 80, такси 100,')
    expect(numberWords('сорок, двадцать')).toBe('40, 20')
  })
})
